def pmf_cdf():
    x = np.arange(4); p = np.array([1, 3, 3, 1]) / 8
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.4, 2.3))
    a1.bar(x, p, width=.35, color=ACC); a1.set_title("PMF: bars, heights add to 1", fontsize=9)
    for xi, pi in zip(x, p):
        a1.text(xi, pi + .01, f"{int(pi * 8)}/8", ha="center", fontsize=8)
    a1.set_xticks(x); a1.set_xlabel("x = number of boys")
    F = np.cumsum(p)
    steps = [(-1, 0, 0), (0, 1, F[0]), (1, 2, F[1]), (2, 3, F[2]), (3, 4, 1)]
    for lo, hi, v in steps:
        a2.plot([lo, hi], [v, v], color=ACC2, lw=2)
        if lo >= 0:
            a2.plot(lo, v, "o", color=ACC2, ms=4)
    a2.set_title("CDF F(x) = P(X ≤ x): a staircase", fontsize=9); a2.set_xticks(x)
    a2.set_yticks([0, .125, .5, .875, 1]); a2.set_yticklabels(["0", "1/8", "4/8", "7/8", "1"]); a2.set_xlabel("x")
    fig.tight_layout()
    return _svg(fig)


